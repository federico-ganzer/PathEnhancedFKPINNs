#!/bin/bash
# Preliminary result set on the manufactured benchmark, submitted as Slurm job arrays.
# Run from the cluster login node after filling slurm/cluster.yaml (copy of cluster.example.yaml).
#
#   bash slurm/prelim.sh check            one GPU job: GPU check, then D4 timing of the heaviest specs
#   bash slurm/prelim.sh times            D4 estimates and suggested walltimes (after check finishes)
#   bash slurm/prelim.sh tune             Astar loss-weight grid: 9 runs, 10k steps, seed 0
#   bash slurm/prelim.sh pick             tuning table and the weights line for configs/manufactured/prelim.yaml
#   bash slurm/prelim.sh main             100 runs; refuses until prelim.yaml holds the picked weights
#   bash slurm/prelim.sh <phase> --dry-run   write the sbatch files without submitting
#
# Runs (5 seeds each; layers configs/base.yaml + configs/manufactured/prelim.yaml):
#   k = 4, dt = 1e-3      B (N = 0, 2) and A0 at M = 125, 500, 2000; Astar and D (N = 2) at k = 1, 4; P.   70
#   k = 16, dt = 2.5e-4   (+ configs/manufactured/prelim_k16.yaml) B (N = 0, 2), A0, Astar, D (N = 2), P.  30
# Astar and D use no paths in training, so the k = 16 set also completes their k = 1, 4, 16 sweep.
# Each array task runs the code checked out when it starts: do not change the checkout while jobs wait.
set -euo pipefail
cd "$(dirname "$0")/.."

PHASE=${1:-}
DRY=${2:-}
CLUSTER=${CLUSTER:-slurm/cluster.yaml}
TUNE_DIR=${TUNE_DIR:-results/manufactured-prelim-tune__Astar}
CUDA_EXTRA=$(sed -n 's/^cuda_extra:[[:space:]]*\([A-Za-z0-9_]*\).*/\1/p' "$CLUSTER")
CUDA_EXTRA=${CUDA_EXTRA:-cuda13}

# Walltime per array task; edit them here. Short limits start sooner (backfill).
# Non-B: D4 on A100 (TF32 matmuls, before full float32) estimated 2.3-3.2 min per full run.
# B: placeholders until D4 times it.
WT_TUNE=00:10:00      # Astar, 10k steps, no kappa or energies
WT_EXACT=00:15:00     # Astar, D, P (k = 4 and k = 16)
WT_A0=00:15:00        # A0, k = 4 (M up to 2000)
WT_B=08:00:00         # B, k = 4 (M up to 2000)
WT_A0_K16=00:15:00    # A0, k = 16
WT_B_K16=12:00:00     # B, k = 16 (paths 4x longer)

P4=(configs/base.yaml configs/manufactured/prelim.yaml)
P16=(configs/base.yaml configs/manufactured/prelim.yaml configs/manufactured/prelim_k16.yaml)
SEEDS=(--seeds 0 1 2 3 4)

# One environment for the login node and every task, so concurrent tasks find it already in sync.
[[ ${NO_SYNC:-0} == 1 ]] || uv sync --frozen --extra "$CUDA_EXTRA"
PY=(uv run --no-sync python)

cl() {  # value of a cluster.yaml key; lists print one item per line
  "${PY[@]}" -c "import sys, yaml
v = yaml.safe_load(open(sys.argv[1])).get(sys.argv[2])
print('\n'.join(map(str, v)) if isinstance(v, list) else ('' if v is None else v))" "$CLUSTER" "$1"
}

submit() {  # submit WALLTIME LAYERS... [run.py options]
  local wt=$1
  shift
  "${PY[@]}" scripts/submit.py "$@" --cluster "$CLUSTER" --walltime "$wt" ${DRY:+--dry-run}
}

tune_table() {  # pick: print the table; main: exit non-zero unless prelim.yaml holds the pick
  "${PY[@]}" - "$1" "$TUNE_DIR" <<'EOF'
import json, math, sys
from pathlib import Path

import yaml

from pathenhancedfkpinn.config import resolve

mode, tdir = sys.argv[1], Path(sys.argv[2])
rows = []
for f in sorted(tdir.glob("*/seed0/final.json")):
    fin = json.loads(f.read_text())
    w = yaml.safe_load((f.parent / "config.yaml").read_text())["weights"]
    e = fin.get("rel_l2_T")
    ok = fin.get("status") == "done" and e is not None and math.isfinite(e)
    rows.append((e if ok else math.inf, w, fin.get("status")))
rows.sort(key=lambda r: r[0])
if mode == "pick":
    print(f"{'data':>6} {'bc':>6} {'rel_l2_T':>12}  status")
    for e, w, s in rows:
        print(f"{w['data']:>6} {w['bc']:>6} {e:>12.4e}  {s}")
done = [r for r in rows if math.isfinite(r[0])]
if len(done) < 9:
    sys.exit(f"{len(done)} of 9 tuning runs finished in {tdir}: wait for the rest, or check the failed ones")
best = done[0][1]
line = f"weights: {{res: {float(best['res'])}, bc: {float(best['bc'])}, data: {float(best['data'])}}}"
cur = resolve(["configs/base.yaml", "configs/manufactured/prelim.yaml"])["weights"]
same = all(float(cur[k]) == float(best[k]) for k in ("res", "bc", "data"))
if mode == "pick":
    print(f"\nsmallest rel_l2_T: data {best['data']}, bc {best['bc']}")
    print(f"line for configs/manufactured/prelim.yaml:\n  {line}")
    print("prelim.yaml already holds these weights" if same else "prelim.yaml does not hold these weights yet")
elif not same:
    sys.exit(f"configs/manufactured/prelim.yaml has weights {cur}, not the tuning pick. Set\n  {line}")
EOF
}

case "$PHASE" in
check)
  LOG=$(cl log_dir)
  mkdir -p slurm/jobs "$LOG"
  JOB=slurm/jobs/prelim_check.sbatch
  cat >"$JOB" <<EOF
#!/bin/bash
# Generated by slurm/prelim.sh check.
#SBATCH --job-name=prelim_check
#SBATCH --account=$(cl account)
#SBATCH --partition=$(cl partition)
#SBATCH --nodes=1
#SBATCH --gres=gpu:$(cl gpus)
#SBATCH --time=00:45:00
#SBATCH --output=$LOG/%x_%j.out
#SBATCH --error=$LOG/%x_%j.err
$(cl extra_sbatch)
set -uo pipefail
cd $(cl repo)
$(cl modules | sed '/./s/^/module load /')
export XLA_PYTHON_CLIENT_PREALLOCATE=false
R="uv run --frozen --extra $CUDA_EXTRA python"
\$R scripts/check_gpu.py --out results/gpu_check_$CUDA_EXTRA.txt || exit 1
d4() { \$R scripts/diagnostics.py d4 "\$@" || echo "[d4 failed] \$*"; }
d4 --layers ${P4[*]} --set arm=Astar
d4 --layers ${P4[*]} --set arm=D arm_opts.N=2
d4 --layers ${P4[*]} --set arm=A0 data.M=2000
d4 --layers ${P4[*]} --set arm=B arm_opts.N=2 data.M=2000
d4 --layers ${P16[*]} --set arm=A0
d4 --layers ${P16[*]} --set arm=B arm_opts.N=2
d4 --layers ${P16[*]} --set arm=D arm_opts.N=2
EOF
  echo "wrote $JOB"
  if [[ -n $DRY ]]; then cat "$JOB"; else sbatch "$JOB"; fi
  ;;
times)
  "${PY[@]}" - <<'EOF'
import json, math
from pathlib import Path

files = sorted(Path("results/diagnostics").glob("d4_manufactured-prelim*.json"))
if not files:
    raise SystemExit("no D4 results yet: run `bash slurm/prelim.sh check` and wait for it")
for f in files:
    d = json.loads(f.read_text())
    peak = (d.get("peak_bytes") or 0) / 2**30
    wt = max(10, math.ceil(1.5 * 60 * d["est_hours"]) + 5)  # minutes; +5: start-up and compiles not in est
    print(f"{d['name']:34s} {d['ms_per_step']:8.1f} ms/step  est {d['est_hours']:6.2f} h  "
          f"peak {peak:5.1f} GiB  walltime >= {wt // 60:02d}:{wt % 60:02d}:00")
EOF
  ;;
tune)
  submit "$WT_TUNE" "${P4[@]}" --set arm=Astar optim.steps=10000 "kappa.steps=[]" energies.n_points=0 \
    --grid weights.data=1,10,100 weights.bc=1,10,100 --seeds 0 --name manufactured-prelim-tune__Astar
  ;;
pick)
  tune_table pick
  ;;
main)
  tune_table main
  # k = 4
  submit "$WT_B" "${P4[@]}" --set arm=B --grid arm_opts.N=0,2 data.M=125,500,2000 "${SEEDS[@]}"
  submit "$WT_A0" "${P4[@]}" --set arm=A0 --grid data.M=125,500,2000 "${SEEDS[@]}"
  submit "$WT_EXACT" "${P4[@]}" --set arm=Astar --grid problem.k=1,4 "${SEEDS[@]}"
  submit "$WT_EXACT" "${P4[@]}" --set arm=D arm_opts.N=2 --grid problem.k=1,4 "${SEEDS[@]}"
  submit "$WT_EXACT" "${P4[@]}" --set arm=P "${SEEDS[@]}"
  # k = 16
  submit "$WT_B_K16" "${P16[@]}" --set arm=B --grid arm_opts.N=0,2 "${SEEDS[@]}"
  submit "$WT_A0_K16" "${P16[@]}" --set arm=A0 "${SEEDS[@]}"
  submit "$WT_EXACT" "${P16[@]}" --set arm=Astar "${SEEDS[@]}"
  submit "$WT_EXACT" "${P16[@]}" --set arm=D arm_opts.N=2 "${SEEDS[@]}"
  submit "$WT_EXACT" "${P16[@]}" --set arm=P "${SEEDS[@]}"
  ;;
*)
  sed -n '2,10p' "$0"
  exit 1
  ;;
esac
